import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROWS = 320;
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'big.js');
let seed = 20260910;
const rand = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };
const pick = (list) => list[Math.floor(rand() * list.length)];
const SYLL = ['ka', 'ro', 'mi', 'te', 'lu', 'sa', 'ne', 'vo', 'ri', 'da', 'po', 'ze'];
const word = (n) => Array.from({ length: n }, () => pick(SYLL)).join('');
const lines = ['// Generated by tools/make-big.mjs. Do not edit by hand.', 'export const ROWS = ['];
for (let i = 0; i < ROWS; i += 1) {
  const name = `${word(2)}-${word(3)}`;
  const region = pick(['north', 'south', 'east', 'west', 'central']);
  const grade = pick(['alpha', 'beta', 'gamma', 'delta']);
  lines.push(`  { id: ${1000 + i}, name: '${name}', region: '${region}', grade: '${grade}', weight: ${Math.round(rand() * 100000) / 1000}, active: ${rand() > 0.3}, tags: ['${word(2)}', '${word(2)}', '${word(2)}'] },`);
}
lines.push('];', '', 'export const byRegion = (region) => ROWS.filter((row) => row.region === region);', '', 'export const heaviest = () => ROWS.reduce((best, row) => (row.weight > best.weight ? row : best), ROWS[0]);', '');
writeFileSync(out, lines.join('\n'), 'utf8');
