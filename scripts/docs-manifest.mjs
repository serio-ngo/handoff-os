#!/usr/bin/env node
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (...parts) => readFileSync(path.join(REPO, ...parts), "utf8");
const readJson = (...parts) => JSON.parse(read(...parts));

const table = (header, rows) => [`| ${header.join(" | ")} |`, `|${header.map(() => "---").join("|")}|`, ...rows].join("\n");

function skills() {
  const dir = path.join(REPO, "plugins", "handoff-os", "skills");
  const rows = readdirSync(dir).sort().map((name) => {
    const text = readFileSync(path.join(dir, name, "SKILL.md"), "utf8");
    const description = (/^description:\s*(.*)$/m.exec(text) || [])[1] || "";
    return `| \`${name}\` | ${description.replace(/^["']|["']$/g, "").length} | ${text.split("\n").length} |`;
  });
  return table(["Skill", "Description chars, always in context", "Body lines, loaded on use"], rows);
}

function hooks() {
  const rows = Object.entries(readJson("plugins", "handoff-os", "hooks", "hooks.json").hooks)
    .flatMap(([event, entries]) => entries.flatMap((entry) => entry.hooks.map((handler) => {
      const script = (/scripts\/[a-z-]+\.mjs/.exec(handler.command) || [])[0];
      return `| \`${event}\` | \`${entry.matcher || "*"}\` | \`${script}\` | ${handler.statusMessage} |`;
    })))
    .sort();
  return table(["Event", "Matcher", "Script", "What it says while it runs"], rows);
}

function policy() {
  const rows = readdirSync(path.join(REPO, "settings")).filter((f) => f.endsWith(".json")).sort().map((file) => {
    const permissions = readJson("settings", file).permissions || {};
    const count = (key) => (permissions[key] || []).length;
    return `| \`${file}\` | ${count("deny")} | ${count("ask")} | ${count("allow")} |`;
  });
  return table(["Template", "Deny", "Ask", "Allow"], rows);
}

function commands() {
  const rows = Object.entries(readJson("package.json").scripts).sort()
    .map(([name, command]) => `| \`npm run ${name}\` | \`${command}\` |`);
  return table(["Command", "Runs"], rows);
}

function config() {
  const rows = Object.entries(readJson("config", "org.example.json")).sort()
    .map(([key, example]) => `| \`${key}\` | ${typeof example} | \`${example}\` |`);
  return table(["Key", "Type", "Example"], rows);
}

export function generateManifest() {
  const version = readJson("plugins", "handoff-os", ".claude-plugin", "plugin.json").version;
  return [
    "# Manifest",
    "",
    `Everything this plugin loads into a session, at version ${version}.`,
    "Generated by `scripts/docs-manifest.mjs` — do not hand-edit; `npm test` fails when it drifts.",
    "",
    "## Skills", "", skills(), "",
    "## Hooks", "", hooks(), "",
    "## Commands", "", commands(), "",
    "## Permission templates", "", policy(), "",
    "## Configuration keys", "", config(), "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = process.argv[2] || path.join(REPO, "docs", "MANIFEST.md");
  writeFileSync(out, generateManifest(), "utf8");
  console.log(`manifest: wrote ${out}`);
}
